def zongce_score(level, award="一等奖", rank=None):
    """综测里某个级别某档奖加多少分。查不到返回 None。

    rank 给定时按团队竞赛排名折算（细则第六条原文）：
    个人加分 = 奖项对应分值 ÷ [1+(排序-1)×0.5]，取前 8 人。
    """
    row = ZONGCE.get(level)
    if not row:
        return None
    v = row.get(award)
    if v is None or rank is None:
        return v
    if rank < 1 or rank > MAX_RANK:
        return None
    return round(v / (1 + (rank - 1) * 0.5), 2)


def tuimo_score(comp_class, rank_level, award="全国一等奖"):
    """推免里某类竞赛某档奖加多少分（含系数与队内排名折算）。

    comp_class: A1 / A2 / B / 其他
    rank_level: 1 起（队内排名）
    """
    raw = TUIMO_COMP.get(award)
    if raw is None:
        return None
    coef = TUIMO_COEF.get(comp_class)
    if coef is None:
        return None
    v = raw * coef
    # 队内排名折算（附件原文：权重依次为 1、0.7、0.5、0.3、0.1、0.1、0.1、0.1）
    if rank_level < 1 or rank_level > len(TUIMO_RANK):
        return None                      # 第 9 名起不计（两份文件都只认前 8 人）
    v *= TUIMO_RANK[rank_level - 1]
    # 其他类累计不超过 20 分
    if comp_class == "其他":
        v = min(v, OTHER_CAP)
    return round(v, 2)


